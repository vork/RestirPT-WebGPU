//   npx tsx validation/scenes/make-m5.ts [outDir] [--only name,name]
// Default output: packages without an environment go to validation/scenes (committed); packages with an HDRI env go to
// validation/out/m5/scenes (gitignored: they embed the downloaded Poly Haven texels, as make-m3c.ts). With an explicit
// outDir every package goes there (the Gate-0 determinism check runs this twice and compares bytes).
//
// Three families:
//  m5s_*  static subset for rungs 3.3–3.5 at 256² (TD28): the M4 packages with render 256² (scene.json render size and
//         name changed, every other byte identical; the env ones are regenerated by make-m3c.ts first).
//  ixs_*  sequence packages for rung 3.6 and the temporal plants (TD27): DENSE frames 0…T−1 (every frame's camera,
//         light matrix/power/size/enabled, env rotation/strength/tint/map), a `sequence {fps, frameCount, testFrames,
//         notes}` block; Mode A, maxBounces 3, 256². Geometry and emissive triangles are static (R17): only the camera,
//         the analytic lights and the env change. Frame k is the state at t = k/24 s, evaluated in closed form here.
//  u8_*   the U8 ladder (TD30): C0c point / C0d spot / C0e rect at 256², b = 0 (pure DI, case (a)) and b = 1 with a
