interface SeqOpts {
  camera: { matrix: number[]; yfov: number };
  maxBounces?: number;
  T: number;
  testFrames: number[];
  notes: string;
  frame: (k: number) => Omit<PackageFrame, 'frame'>;
  envMaps?: { id: string; env: EnvironmentData }[];
  extra?: Record<string, unknown>;
}

async function writePkg(dir: string, scene: SceneData, o: Parameters<typeof exportScenePackage>[1], extra?: Record<string, unknown>): Promise<void> {
  const pkg = await exportScenePackage(scene, o);
  if (extra) pkg.files.set('scene.json', new TextEncoder().encode(JSON.stringify({ ...pkg.json, ...extra }, null, 1)));
  rmSync(dir, { recursive: true, force: true });
  mkdirSync(dir, { recursive: true });
  for (const [k, b] of pkg.files) writeFileSync(path.join(dir, k), b);
}

async function writeSequence(name: string, scene: SceneData, o: SeqOpts): Promise<void> {
  if (o.testFrames.some((t) => !(Number.isInteger(t) && t >= 0 && t < o.T))) throw new Error(`${name}: test frame outside 0..${o.T - 1}`);
  const frames: PackageFrame[] = range(o.T).map((k) => ({ frame: k, ...o.frame(k) }));
  const sequence: PackageSequence = { fps: FPS, frameCount: o.T, testFrames: o.testFrames, notes: o.notes };
  const out = scene.env ? OUT_ENV : OUT_STATIC;
  await writePkg(path.join(out, name), scene, {
    camera: o.camera, render: { width: 256, height: 256, maxBounces: o.maxBounces ?? 3 }, lightMode: 'A', flatShaded: true, name,
    frames, sequence, ...(o.envMaps ? { envMaps: o.envMaps } : {}), source: SRC(o.notes),
  }, { tier: 'tight', ...o.extra });
}

