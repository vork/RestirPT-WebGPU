export const M5_PACKAGES = (): string[] => gens.map(([n]) => n);
/** Packages written to the env output (validation/out/m5/scenes by default). */
export const M5_ENV_PACKAGES = ['m5s_c0q_openbox_b13', 'm5s_overcast_rect_b3', 'ixs_h_envrot_256', 'ixs_i_envradio_256', 'ixs_j_envcombo_256', 'ixs_k_envswap_256'];

async function main(): Promise<void> {
  const todo = gens.filter(([n]) => !ONLY || ONLY.has(n));
  if (ONLY && todo.length !== ONLY.size) throw new Error(`unknown package(s): ${[...ONLY].filter((n) => !gens.some(([g]) => g === n)).join(', ')}`);
  try {
    for (const [name, g] of todo) {
      await g();
      console.log(`wrote ${path.relative(ROOT, path.join(M5_ENV_PACKAGES.includes(name) ? OUT_ENV : OUT_STATIC, name))}`);
    }
  } finally {
    if (m3cDir) rmSync(m3cDir, { recursive: true, force: true });
  }
}

if (process.argv[1] && import.meta.url === new URL(`file://${path.resolve(process.argv[1])}`).href) {
  main().catch((e) => { console.error(e); process.exit(1); });
}
