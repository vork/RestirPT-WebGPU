/** Copy a package and set render 256² + name (every other byte identical). */
function resizePackage(srcDir: string, dst: string, name: string, srcName: string): void {
  if (!existsSync(path.join(srcDir, 'scene.json'))) throw new Error(`${srcDir}: missing package`);
  rmSync(dst, { recursive: true, force: true });
  mkdirSync(dst, { recursive: true });
  for (const f of readdirSync(srcDir).sort()) if (f !== 'scene.json') cpSync(path.join(srcDir, f), path.join(dst, f));
  const json = JSON.parse(readFileSync(path.join(srcDir, 'scene.json'), 'utf8')) as Record<string, any>;
  const out = { ...json, name, render: { ...json.render, width: 256, height: 256 }, m5: { derivedFrom: srcName, change: 'render 256x256 (restir-temporal-api.md TD28)', generator: 'validation/scenes/make-m5.ts' } };
  writeFileSync(path.join(dst, 'scene.json'), JSON.stringify(out, null, 1));
}

let m3cDir: string | undefined;
/** make-m3c.ts output for the env sources (generated once per make-m5 run into a scratch dir). */
function m3cSource(name: string): string {
  if (!m3cDir) {
    m3cDir = path.join(OUT_ENV, '.m3c-src');
    const want = M5S.filter((s) => s.env).map((s) => s.src).join(',');
    const r = spawnSync('npx', ['tsx', 'validation/scenes/make-m3c.ts', m3cDir, '--only', want], { cwd: ROOT, encoding: 'utf8' });
    if (r.status !== 0) throw new Error(`make-m3c.ts failed: ${r.stdout}${r.stderr}`);
  }
  return path.join(m3cDir, name);
}

