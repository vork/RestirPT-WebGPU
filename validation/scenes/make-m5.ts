type Cornell = Awaited<ReturnType<typeof cornellBase>>;
const matIndex = (mats: readonly MaterialData[], name: string) => {
  const i = mats.findIndex((m) => m.name === name);
  if (i < 0) throw new Error(`material ${name} missing`);
  return i;
};

/** The Cornell box (+ an optional occluder box on the floor, + an optional GGX floor material). */
function cornellWith(c: Cornell, o: { box?: boolean; ggxFloor?: number; open?: boolean } = {}): { mb: MeshBuilder; mats: MaterialData[] } {
  const g = c.geometry;
  const mats = [...c.materials];
  const white = matIndex(mats, 'white');
  let floorMat = white;
  if (o.ggxFloor !== undefined) {
    mats.push(v1('floor_ggx', { diffuse: [0.6, 0.6, 0.6], glossy: [0.8, 0.8, 0.8], roughness: o.ggxFloor, mix: 0.5 }));
    floorMat = mats.length - 1;
  }
  let ymax = -Infinity;
  for (let i = 1; i < g.positions.length; i += 3) ymax = Math.max(ymax, g.positions[i]);
  const mb = new MeshBuilder();
  for (let t = 0; t < g.indices.length / 3; t++) {
    const P = (k: number): V3 => { const i = g.indices[3 * t + k]; return [g.positions[3 * i], g.positions[3 * i + 1], g.positions[3 * i + 2]]; };
    const ys = [0, 1, 2].map((k) => P(k)[1]);
    if (o.open && ys.every((y) => Math.abs(y - ymax) < 1e-6)) continue;            // open to the sky: drop the ceiling
    const isFloor = ys.every((y) => Math.abs(y) < 1e-6);
    mb.tri(P(0), P(1), P(2), isFloor ? floorMat : g.triMaterial[t]);
  }
  // occluder: a white box standing on the floor slightly behind the centre (shadows, disocclusions)
  if (o.box) mb.box([-0.02, 0, -0.16], [0.10, 0.20, -0.04], white, { rotY: 12 * deg, omit: ['-y'] });
  return { mb, mats };
}

const envBase = { strength: 1, tint: [1, 1, 1] as V3, rotationZ: 0, visibleToCamera: true };
const hdriCache = new Map<string, EnvironmentData>();
function hdri(id: string, rotationZ = 0): EnvironmentData {
  let e = hdriCache.get(id);
  if (!e) {
    const file = path.join(HDRI_DIR, `${id}_1k.hdr`);
    let bytes: Uint8Array;
    try { bytes = new Uint8Array(readFileSync(file)); } catch { throw new Error(`${file} missing: run npx tsx validation/assets/fetch_hdris.ts`); }
    const img = decodeHdr(bytes);
    e = { ...envBase, name: `${id}_1k`, width: img.width, height: img.height, texels: img.texels };
    hdriCache.set(id, e);
  }
  return { ...e, rotationZ };
}
/** A different map for the ixs_k swap: the same HDRI box-filtered 2× (half resolution; a different texture and
 *  importance table, tight tier). */
function halfRes(e: EnvironmentData): EnvironmentData {
  const W = e.width / 2, H = e.height / 2;
  const t = new Float32Array(W * H * 4);
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) {
    for (let c = 0; c < 3; c++) {
      let s = 0;
      for (const [dx, dy] of [[0, 0], [1, 0], [0, 1], [1, 1]]) s += e.texels[4 * ((2 * y + dy) * e.width + 2 * x + dx) + c];
      t[4 * (y * W + x) + c] = Math.fround(s / 4);
    }
    t[4 * (y * W + x) + 3] = 1;
  }
  return { ...e, name: `${e.name}_half`, width: W, height: H, texels: t };
}

